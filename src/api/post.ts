import { apiClient } from "./client";
import type {
  CreatePostRequest,
  DataPostDetail,
  DataPostPreview,
  GetMarketplacePostsParams,
  PageResponse,
  UpdatePostRequest,
} from "../types/post";

export async function getMarketplacePosts(
  params: GetMarketplacePostsParams = {},
): Promise<PageResponse<DataPostPreview>> {
  const response = await apiClient.get<PageResponse<DataPostPreview>>(
    "/api/datapost/marketplace",
    {
      params: {
        page: params.page ?? 0,
        size: params.size ?? 12,
        genre: params.genre,
        sort: params.sort ?? "newest",
      },
    },
  );

  return response.data;
}

export async function getDataPostById(id: number): Promise<DataPostDetail> {
  const response = await apiClient.get<DataPostDetail>(
    `/api/datapost/posts/${id}`,
  );

  return response.data;
}

export async function createPost(
  data: CreatePostRequest,
): Promise<DataPostDetail> {
  const formData = new FormData();

  formData.append("userId", String(data.userId));
  formData.append("genre", data.genre);
  formData.append("title", data.title);

  // Summary is now AI-generated by the backend.
  // Do not send user-input summary.
  // formData.append("summary", data.summary ?? "");

  formData.append("price", String(data.price));
  formData.append("file", data.file);

  const response = await apiClient.post<DataPostDetail>(
    "/api/datapost",
    formData,
  );

  return response.data;
}

export async function getPostsByUserId(
  userId: number,
  page: number,
  size: number,
): Promise<PageResponse<DataPostDetail>> {
  const res = await apiClient.get<PageResponse<DataPostDetail>>(
    `/api/datapost/user/${userId}`,
    {
      params: {
        page,
        size,
      },
    },
  );

  return res.data;
}

export async function updatePost(
  data: UpdatePostRequest,
): Promise<DataPostDetail> {
  const formData = new FormData();

  formData.append("userId", String(data.userId));
  formData.append("title", data.title);

  // Summary is now AI-generated by the backend.
  // Do not send user-input summary.
  // formData.append("summary", data.summary ?? "");

  formData.append("price", String(data.price));
  formData.append("genre", data.genre);

  if (data.file) {
    formData.append("file", data.file);
  }

  const response = await apiClient.put<DataPostDetail>(
    `/api/datapost/posts/${data.postId}`,
    formData,
  );

  return response.data;
}

export async function deletePost(
  postId: number,
  userId: number,
): Promise<void> {
  await apiClient.delete(`/api/datapost/posts/${postId}`, {
    params: { userId },
  });
}
